package com.mediconnect.entity;

import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.OnDelete;
import org.hibernate.annotations.OnDeleteAction;

import java.time.LocalDate;

/**
 * A person who receives care. Phone/email are NOT unique: relatives (a parent booking for a child)
 * legitimately share them. Detect duplicates (name + date of birth + phone) in the service.
 * gender: MALE | FEMALE | OTHER.  bloodGroup (optional): A_POSITIVE, A_NEGATIVE, B_POSITIVE, B_NEGATIVE,
 * AB_POSITIVE, AB_NEGATIVE, O_POSITIVE, O_NEGATIVE. Both guarded by CHECK constraints.
 */
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
@Builder
@Entity
@Table(name = "patients", check = {
        @CheckConstraint(name = "ck_patients_gender", constraint = "gender IN ('MALE', 'FEMALE', 'OTHER')"),
        @CheckConstraint(name = "ck_patients_blood_group", constraint = "blood_group IS NULL OR blood_group IN ("
                + "'A_POSITIVE', 'A_NEGATIVE', 'B_POSITIVE', 'B_NEGATIVE', "
                + "'AB_POSITIVE', 'AB_NEGATIVE', 'O_POSITIVE', 'O_NEGATIVE')")
})
public class Patient {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "patient_id")
    private Long id;

    /** Hospital-facing patient number (UHID). Generated by the service from the patient_uhid_seq sequence. */
    @Column(name = "uhid", nullable = false, unique = true, length = 20)
    private String uhid;

    @Column(name = "full_name", nullable = false, length = 150)
    private String fullName;

    @Column(name = "date_of_birth", nullable = false)
    private LocalDate dateOfBirth;

    @Column(name = "gender", nullable = false, length = 10)
    private String gender;

    @Column(name = "phone", nullable = false, length = 30)
    private String phone;

    @Column(name = "email", length = 150)
    private String email;

    @Column(name = "blood_group", length = 15)
    private String bloodGroup;

    @Column(name = "address_line1", length = 200)
    private String addressLine1;

    @Column(name = "address_line2", length = 200)
    private String addressLine2;

    @Column(name = "city", length = 100)
    private String city;

    @Column(name = "state", length = 100)
    private String state;

    @Column(name = "postal_code", length = 20)
    private String postalCode;

    @Column(name = "emergency_contact_name", length = 150)
    private String emergencyContactName;

    @Column(name = "emergency_contact_phone", length = 30)
    private String emergencyContactPhone;

    @Column(name = "active", nullable = false)
    @Builder.Default
    private boolean active = true;

    /**
     * The patient login that manages this record (the person themselves, or a parent for a child).
     * Null for walk-ins registered at reception; linked automatically when someone logs in with this phone.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "owner_user_id")
    @OnDelete(action = OnDeleteAction.SET_NULL)
    private User owner;
}
